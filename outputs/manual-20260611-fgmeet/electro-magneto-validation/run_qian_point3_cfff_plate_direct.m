function values = average_by_layer(vec, n_layer)
values = nan(n_layer, 1);
if isempty(vec) || n_layer < 1
    return;
end
for i = 1:n_layer
    layer_values = vec(i:n_layer:end);
    layer_values = layer_values(~isnan(layer_values));
    if ~isempty(layer_values)
        values(i) = full(mean(layer_values));
    end
end
end

function s = span_value(vec)
vals = vec(~isnan(vec));
if isempty(vals)
    s = NaN;
else
    s = full(max(vals) - min(vals));
end
end
